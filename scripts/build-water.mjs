#!/usr/bin/env node
/**
 * Builds water-data.js (loaded by index.html) from the water-rates exports in scripts/data/.
 *
 *   node scripts/build-water.mjs
 *   node scripts/build-water.mjs --latest path/latest.csv --history path/history.csv
 *
 * Coordinates: exact city pins (water-geo.mjs) > exact geocoded pins (scripts/water-coords.json, optional,
 * made by geocode-water.mjs) > province-center spiral (approximate).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PROV, ISLAND, CITY, INLAND, prettyProv, PROV_DISPLAY } from "./water-geo.mjs";

const DIR = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.resolve(DIR, "..");
const args = process.argv.slice(2), opt = n => { const i = args.indexOf("--" + n); return i >= 0 ? args[i + 1] : null; };
const LATEST = opt("latest") || path.join(DIR, "data/water_districts_latest.csv");
const HISTORY = opt("history") || path.join(DIR, "data/water_districts_history.csv");
const COORDS_FILE = path.join(DIR, "water-coords.json");

function parseCSV(text) {
  const rows = []; let row = [], f = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true;
    else if (c === ",") { row.push(f); f = ""; }
    else if (c === "\n") { row.push(f.replace(/\r$/, "")); rows.push(row); row = []; f = ""; }
    else f += c;
  }
  if (f || row.length) { row.push(f.replace(/\r$/, "")); rows.push(row); }
  const h = rows.shift();
  return rows.filter(r => r.length === h.length).map(r => Object.fromEntries(h.map((k, i) => [k, r[i]])));
}
const num = v => { const n = parseFloat(v); return Number.isFinite(n) ? n : null; };
const r2 = n => n == null ? null : Math.round(n * 100) / 100;

const latest = parseCSV(fs.readFileSync(LATEST, "utf8"));
const hist = parseCSV(fs.readFileSync(HISTORY, "utf8"));
const exact = fs.existsSync(COORDS_FILE) ? JSON.parse(fs.readFileSync(COORDS_FILE, "utf8")) : {};

// periods newest-first
const periods = [...new Set(hist.map(r => r.period))].sort().reverse();
const pIdx = new Map(periods.map((p, i) => [p, i]));
const H = {};
for (const r of hist) {
  const a = H[r.ccc] || (H[r.ccc] = new Array(periods.length).fill(null));
  const v = num(r.cost_20cum); a[pIdx.get(r.period)] = v > 0 ? r2(v) : null;
}

// coordinates
const byProv = {};
const rows = latest.map(r => {
  const key = r.name + "|" + r.province, e = exact[r.ccc];
  let ll = CITY[key] || (e && [e[0], e[1]]), ex = ll ? 1 : 0;
  const o = { r, ll, ex }; if (!ex) (byProv[r.province] || (byProv[r.province] = [])).push(o);
  return o;
});
const missingProv = new Set();
for (const [p, list] of Object.entries(byProv)) {
  const ov = INLAND[p], c = ov || PROV[p]; if (!c) { missingProv.add(p); continue; }
  list.sort((a, b) => a.r.name.localeCompare(b.r.name));
  const GA = Math.PI * (3 - Math.sqrt(5));              // golden angle spiral
  list.forEach((o, i) => {
    const k = ov ? Math.min(0.045, ov[2] / Math.sqrt(list.length + 0.6)) : 0.045;
    const rad = k * Math.sqrt(i + 0.6), th = i * GA;  // ~5 km per step, so pins fan out without overlapping
    o.ll = [c[0] + rad * Math.sin(th), c[1] + rad * Math.cos(th) / Math.cos(c[0] * Math.PI / 180)];
  });
}
if (missingProv.size) { console.error("No center for province:", [...missingProv]); process.exit(1); }

const d = rows.map(({ r, ll, ex }) => {
  const h = H[r.ccc];
  return [r.ccc, r.name, prettyProv(r.province), ISLAND[r.region] || "L", r.category || "", r.as_of || "", r.date_approved || "",
    num(r.service_connections), num(r.population_served), r2(num(r.ave_consumption_m3)),
    num(r.min_charge_10cum), num(r.rate_11_20), num(r.rate_21_30), num(r.rate_31_40), num(r.rate_41_50), num(r.rate_51_up),
    num(r.cost_20cum), num(r.cost_30cum), +ll[0].toFixed(4), +ll[1].toFixed(4), ex, r.flags || ""];
});
d.sort((a, b) => a[2].localeCompare(b[2]) || a[1].localeCompare(b[1]));

const alias = {};
for (const [raw, shown] of Object.entries(PROV_DISPLAY)) alias[shown] = raw;
const src = JSON.parse(fs.readFileSync(path.join(DIR, "data/water_districts_latest.json"), "utf8")).source || "";
const cols = "ccc,name,province,island,category,as_of,rates_approved,connections,population,avg_m3,min10,r11_20,r21_30,r31_40,r41_50,r51_up,cost20,cost30,lat,lon,exact,flags";
const out = `// Generated by scripts/build-water.mjs. Do not edit by hand; re-run the script instead.
// d[]: ${cols}
// h{ccc}: bill at 20 m3 per period, same order as periods[] (newest first); null = no rate
window.WATER={source:${JSON.stringify(src)},asOf:${JSON.stringify(periods[0])},periods:${JSON.stringify(periods)},
alias:${JSON.stringify(alias)},
d:[
${d.map(x => JSON.stringify(x)).join(",\n")}
],
h:{
${Object.entries(H).map(([k, v]) => JSON.stringify(k) + ":" + JSON.stringify(v)).join(",\n")}
}};
`;
fs.writeFileSync(path.join(ROOT, "water-data.js"), out);
const nEx = d.filter(x => x[20]).length;
console.log(`water-data.js: ${d.length} districts (${nEx} exact pins, ${d.length - nEx} approximate), ${periods.length} periods, ${(out.length / 1024).toFixed(0)} KB`);
